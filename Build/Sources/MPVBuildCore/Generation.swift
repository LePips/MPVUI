import Foundation

enum Generator {
    static let begin = "// MPVBUILD_BINARY_TARGETS_BEGIN"
    static let end = "// MPVBUILD_BINARY_TARGETS_END"
    static func artifactPrefix(_ native: NativeLock) -> String {
        native.publication.nativePrefix == "native-" ? "artifacts-" : native.publication.nativePrefix
    }

    static func replace(_ text: String, begin: String, end: String, body: String) throws -> String {
        let lines = text.components(separatedBy: "\n")
        let starts = lines.indices.filter { lines[$0].trimmingCharacters(in: .whitespaces).hasPrefix(begin) }
        let ends = lines.indices.filter { lines[$0].trimmingCharacters(in: .whitespaces).hasPrefix(end) }
        try require(
            starts.count == 1 && ends.count == 1 && starts[0] < ends[0],
            "Malformed, duplicate, missing or reversed generation markers: \(begin)"
        )
        return (Array(lines[..<starts[0]]) + body.components(separatedBy: "\n") + Array(lines[(ends[0] + 1)...])).joined(separator: "\n")
    }

    static func quote(_ value: String) throws -> String {
        try require(!value.unicodeScalars.contains { $0.value < 32 }, "Control character in Swift literal")
        return try String(decoding: canonical(value), as: UTF8.self)
    }

    static func isVersionTag(_ tag: String) -> Bool {
        tag.range(of: #"^v?(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)(-[0-9A-Za-z.-]+)?$"#, options: .regularExpression) != nil
    }

    static func releaseID(native: NativeLock, fingerprint: String, tag: String?) throws -> String {
        try hex(fingerprint)
        if let tag {
            try require(isVersionTag(tag), "Release tag must be SemVer")
            return tag
        }
        return artifactPrefix(native) + fingerprint
    }

    static func validate(_ index: ArtifactIndex, native: NativeLock, release: Bool) throws {
        try require(index.schemaVersion == 2, "Unsupported artifact index schema")
        try hex(index.nativeInputFingerprint)
        try require(
            index.releaseID == artifactPrefix(native) + index.nativeInputFingerprint || index.releaseID == native.publication
                .nativePrefix + index.nativeInputFingerprint || isVersionTag(index.releaseID),
            "Artifact release identity mismatch"
        )
        try require(index.provenancePath == "Libmpv.xcframework/provenance.json", "Invalid embedded provenance path")
        try unique(index.products.map(\.target), "published products")
        try require(
            Set(index.products.map(\.target)) == Set(ProductDefinition.all.map(\.target)),
            "Artifact release must contain exactly one combined Libmpv XCFramework"
        )
        for artifact in index.products {
            try hex(artifact.sha256)
            try https(artifact.url)
            guard let definition = ProductDefinition.all.first(where: { $0.target == artifact.target })
            else { throw BuildError("Unknown build product") }
            try require(
                artifact.framework == definition.framework && artifact.module == definition.framework && artifact.archive == definition
                    .archive,
                "Product/module/archive naming mismatch"
            )
            if release {
                try require(artifact.slices == native.slices, "Partial development artifact cannot be adopted or released")
            }
            let expectedURL = "https://github.com/\(native.publication.repository)/releases/download/\(index.releaseID)/\(artifact.archive)"
            try require(artifact.url == expectedURL, "Asset URL differs from publication identity")
        }
        try require(index.dependencies.isEmpty, "Combined release must not require external binary downloads")
    }

    static func manifest(_ original: String, index: ArtifactIndex, local: [String: URL]? = nil, packageRoot: URL? = nil) throws -> String {
        try require(local == nil || packageRoot != nil, "Local manifest generation requires its package root")
        let text = original
        var targets: [String] = []
        for artifact in index.products {
            if let path = local?[artifact.target] {
                try targets
                    .append(
                        "    .binaryTarget(name: \(quote(artifact.target)), path: \(quote(relativePath(from: packageRoot!, to: path)))),"
                    )
            } else {
                try targets
                    .append(
                        "    .binaryTarget(name: \(quote(artifact.target)), url: \(quote(artifact.url)), checksum: \(quote(artifact.sha256))),"
                    )
            }
        }
        let body = begin +
            " — Generated by Build/mpvbuild; selection: \(local == nil ? "remote" : "local")\nprivate let binaryTargets: [Target] = [\n" +
            targets.joined(separator: "\n") + "\n]\n" + end
        return try replace(text, begin: begin, end: end, body: body)
    }

    static func localLinks(_ paths: [String: URL], package: URL, identity: String) throws -> [String: URL] {
        let store = try ManagedStore(root: package.appendingPathComponent(".build/mpvbuild-local"))
        let lease = try FileLock(store.path("locks/\(identity).lock"))
        defer { withExtendedLifetime(lease) {} }
        let directory = try store.path("selections/" + identity)
        try mkdir(directory)
        var result: [String: URL] = [:]
        for name in paths.keys.sorted() {
            let link = directory.appendingPathComponent(name + ".xcframework")
            if let destination = try? fm.destinationOfSymbolicLink(atPath: link.path) {
                try require(destination == paths[name]!.path, "Local selection link differs from its identity")
            } else {
                try require(!exists(link), "Local selection path is not an owned link")
                try fm.createSymbolicLink(at: link, withDestinationURL: paths[name]!)
            }
            result[name] = link
        }
        return result
    }

    static func inventory(_ native: NativeLock) -> String {
        "# Libmpv platform inventory\n\nGenerated by `Build/mpvbuild generate`. Library deployment floors are separate from the SwiftUI wrapper's availability.\n\n| Slice | Architectures | Identifier | Library minimum | SDK |\n| --- | --- | --- | --- | --- |\n" +
            native.slices
            .map { "| \($0.id) | \($0.architectures.joined(separator: ", ")) | \($0.identifier) | \($0.minimumOS) | \($0.sdk) |" }
            .joined(separator: "\n") + "\n\n\(native.slices.count) slices; \(native.slices.reduce(0) { $0 + $1.architectures.count }) thin architecture builds.\n"
    }

    static func files(root: URL, native: NativeLock, index: ArtifactIndex) throws -> [String: Data] {
        try validate(index, native: native, release: true)
        let original = try String(contentsOf: root.appendingPathComponent("Package.swift"), encoding: .utf8)
        let manifest = try manifest(original, index: index)
        try require(self.manifest(manifest, index: index) == manifest, "Manifest generation is not idempotent")
        return inventoryFiles(native).merging(["Package.swift": Data(manifest.utf8)]) { _, new in new }
    }

    static func inventoryFiles(_ native: NativeLock) -> [String: Data] {
        ["Build/PLATFORMS.md": Data(inventory(native).utf8)]
    }

    static func generate(root: URL, native: NativeLock, runner: Runner, check: Bool, inventoryOnly: Bool = false) throws {
        let transaction = try FileTransaction(root: root)
        defer { withExtendedLifetime(transaction) {} }
        let indexURL = root.appendingPathComponent("Build/Artifacts.lock.json")
        let outputs: [String: Data]
        if inventoryOnly {
            outputs = inventoryFiles(native)
        } else {
            try require(
                exists(indexURL),
                "No artifact release has been adopted. Build a release candidate, publish it, then run release adopt --release ID."
            )
            let index = try read(ArtifactIndex.self, indexURL)
            outputs = try files(root: root, native: native, index: index)
        }
        if check {
            let package = try runner.run("/usr/bin/swift", ["package", "--package-path", root.path, "dump-package"])
            try requireRemoteBinaryTargets(Data(package.utf8))
            for (path, content) in outputs {
                try require(
                    (try? Data(contentsOf: root.appendingPathComponent(path))) == content,
                    "Generated file drift (or local selection): \(path)"
                )
            }
        } else {
            if let manifest = outputs["Package.swift"] {
                try evaluate(manifest, runner: runner)
            }
            try transaction.commit(outputs)
        }
    }

    static func requireRemoteBinaryTargets(_ package: Data) throws {
        guard let object = try JSONSerialization.jsonObject(with: package) as? [String: Any],
              let targets = object["targets"] as? [[String: Any]] else { throw BuildError("Invalid evaluated package targets") }
        for target in targets where target["type"] as? String == "binary" {
            try require(
                target["path"] == nil && target["url"] is String && target["checksum"] is String,
                "Committed local binary selection is not allowed: \(target["name"] ?? "unknown")"
            )
        }
    }

    static func evaluate(_ manifest: Data, runner: Runner) throws {
        let stage = runner.logs.appendingPathComponent("manifest-\(UUID().uuidString)")
        try mkdir(stage)
        defer { try? remove(stage) }
        try put(manifest, stage.appendingPathComponent("Package.swift"))
        let data = try runner.run("/usr/bin/swift", ["package", "--package-path", stage.path, "dump-package"])
        try require(
            (JSONSerialization.jsonObject(with: Data(data.utf8)) as? [String: Any])?["name"] as? String == "MPVUI",
            "Evaluated the wrong Swift package"
        )
    }
}

/// Journaled multi-file updates: a crash before the journal is removed is recovered by restoring the old set.
final class FileTransaction {
    private let root: URL
    private let journal: URL
    private let lock: FileLock
    private struct Backup: Codable { let path: String
        let existed: Bool
        let contents: Data
    }

    init(root: URL) throws {
        self.root = root
        journal = root.appendingPathComponent(".build/mpvbuild-generation-journal.json")
        lock = try FileLock(root.appendingPathComponent(".build/mpvbuild-generation.lock"))
        if exists(journal) {
            try restore()
        }
    }

    private func restore() throws {
        for entry in try read([Backup].self, journal) {
            let file = try contained(root, entry.path)
            if entry.existed {
                try put(entry.contents, file)
            } else {
                try remove(file)
            }
        }
        try remove(journal)
    }

    func commit(_ outputs: [String: Data]) throws {
        let backups = try outputs.keys.sorted().map { path in
            let file = try contained(root, path)
            return try Backup(path: path, existed: exists(file), contents: exists(file) ? Data(contentsOf: file) : Data())
        }
        try write(backups, journal)
        do {
            for path in outputs.keys.sorted() {
                try put(outputs[path]!, contained(root, path))
            }
            try remove(journal)
        } catch { try restore()
            throw error
        }
    }
}
